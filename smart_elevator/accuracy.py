"""Measure the YOLO person detector's accuracy and save it to accuracy_results.py.

Detectors are scored with precision, recall and mAP rather than a single
"accuracy". Only the person class is evaluated, matching what the app uses.

    python -m smart_elevator.accuracy                 # COCO128 (auto-downloaded)
    python -m smart_elevator.accuracy --data my.yaml  # your own labelled lobby clips
"""

import argparse
from datetime import datetime
from pathlib import Path
from pprint import pformat

try:
    from .config import CONFIG
    from .detector import PERSON_CLASS_ID
except ImportError:  # Supports running accuracy.py directly from this directory.
    from config import CONFIG
    from detector import PERSON_CLASS_ID


RESULTS_PATH = Path(__file__).resolve().parent / "accuracy_results.py"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--model", type=Path, default=CONFIG.model_path)
    parser.add_argument("--data", default="coco128.yaml", help="Ultralytics dataset YAML")
    parser.add_argument("--imgsz", type=int, default=CONFIG.inference_image_size)
    parser.add_argument("--conf", type=float, default=0.001, help="Use 0.001 for standard mAP")
    parser.add_argument("--device", default=CONFIG.device)
    parser.add_argument("--output", type=Path, default=RESULTS_PATH)
    return parser.parse_args()


def evaluate(args: argparse.Namespace) -> dict:
    from ultralytics import YOLO

    if not args.model.exists():
        raise FileNotFoundError(f"YOLO model not found at {args.model}. Run setup_model.py.")

    metrics = YOLO(str(args.model)).val(
        data=args.data,
        classes=[PERSON_CLASS_ID],
        imgsz=args.imgsz,
        conf=args.conf,
        device=args.device,
        plots=False,
        verbose=False,
    )
    box = metrics.box
    precision, recall = float(box.mp), float(box.mr)
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "model": args.model.name,
        "dataset": args.data,
        "image_size": args.imgsz,
        "evaluated_class": "person",
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
        "map50": round(float(box.map50), 4),
        "map50_95": round(float(box.map), 4),
        "inference_ms_per_image": round(float(metrics.speed["inference"]), 2),
        "measured_at": datetime.now().isoformat(timespec="seconds"),
    }


def save(results: dict, output: Path) -> None:
    output.write_text(
        '"""Person-detection accuracy, generated by accuracy.py. Do not edit by hand."""\n\n'
        f"ACCURACY = {pformat(results, sort_dicts=False)}\n"
    )


def main() -> None:
    args = parse_args()
    results = evaluate(args)
    save(results, args.output)
    for key, value in results.items():
        print(f"{key:>24}: {value}")
    print(f"Saved to {args.output}")


if __name__ == "__main__":
    main()
